from pydantic import BaseModel, Field
from typing import Annotated, Literal
from operator import add

class AgentSchema(BaseModel):
    messages: Annotated[list,add] = Field(..., description="List of messages to be processed by the agent")
    user_question: str = Field(..., description="User question")
    curated_question: str = Field(..., description="Curated user question")
    prompt_query_context: str = Field(..., description="A detailed prompt with SQL DB context that will help agent to generate SQL query")
    is_safe: Literal["Yes", "No"] = Field(...,description="Indicates whether the generated SQL query is safe to execute or not")
    justification: str = Field(..., description="Justification for the generated SQL query")
    generated_sql_query: str = Field(...,description="The SQL query generated by the agent based on the curated question and prompt context")
    sql_query_execution_result: str = Field(..., description="The result of executing the generated SQL query on the database")
    final_answer: str = Field(..., description="The final answer generated by the agent based on SQL query")

class JudgeSchema(BaseModel):
    answer: Literal["Yes", "No"] = Field(..., description="Indicate whether the generated SQL query is safe to execute or not")
    justification: str = Field(..., description="Justification from the judge regarding the SQL query")


class ETLAgentSchema(BaseModel):
    messages: Annotated[list,add] = Field(..., description="List of messages to be processed by the agent")


class RouterSchema(BaseModel):
    answer: Literal["SQL", "ETL"] = Field(..., description="Indicate whether the user's question is related to SQL or ETL operations")
    justification: str = Field(..., description="Justification for your decision")
    

class DataAgentSchema(BaseModel):
    messages: Annotated[list,add] = Field(..., description="List of messages to be processed by the agent")
    router_response: str = Field(..., description="The response from the router indicating whether to route to SQL or ETL operations")
